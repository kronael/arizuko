-- Every stored instant carries a fixed-width nine-digit fraction, so
-- lexicographic order over it IS chronological order (core.TSLayout).
--
-- The three the message feed depends on are one mechanism: a message's instant
-- is the subject of two cursors, the dispatch feed's and the observe feed's, and
-- each cursor is a copy of some row's instant compared back against the column
-- with `>`. A stripped fraction makes that comparison disagree with time inside
-- one second — `.` is 0x2E, `Z` is 0x5A — and a cursor only moves forward, so the
-- row is skipped for good (L97).
--
-- A PARTIAL state is worse than either whole one. Padding a cursor makes it
-- shorter than the unpadded rows of its own second, so cursors padded while rows
-- are not re-feed consumed messages: 28 on krons, 27 on marinade, 33 on sloth,
-- measured against copies of the live files.
--
-- `messages`, `chats` and `sessions` are objstore entities rather than tables
-- this chain creates: the driver makes them, from the declaration beside the
-- code writing them (store.EnsureEntities, spec 6/37 step 7). A message's
-- instant is the leading field of its sort key and a cursor is an attribute, so
-- no UPDATE of three columns can reach either.
--
-- `arizuko migrate-hot` renders both as it carries them, through the one writer
-- that enforces the layout (objstore.OrderedSort), and then reads the result
-- back: it derives each chat's cursor as the greatest key at or before the
-- instant the old one held, and REFUSES the move unless every cursor leaves
-- exactly the set of rows unfed that it left before. Rows before cursors is no
-- longer an order somebody preserves — it is the only order the shape allows,
-- and the set comparison is what proves it held.
