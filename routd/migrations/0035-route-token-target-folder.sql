-- route_tokens.target_folder — the folder the token DELIVERS to (spec 5/W).
-- owner_folder bounds revocation and may differ from the delivery target, so it
-- cannot answer "where does this payload go".
--
-- Without it the answer comes from the JID grammar alone, which is ambiguous as
-- soon as the mint adds a suffix: `web:t/sfx` is byte-identical to a no-suffix
-- mint at folder `t/sfx`, and `hook:a/b/c` is both (folder `a/b`, source `c`)
-- and (folder `a`, source `b`, suffix `c`). routd resolved the wrong folder,
-- found no group, and onbod parked the payload in the admission queue (BUGS
-- L4). The mint knows the target; it records it.
--
-- A token that carries no target_folder keeps the grammar
-- (groupfolder.JidFolder), which is what it was minted under.
--
-- `route_tokens` is an objstore entity rather than a table this chain creates:
-- the driver makes it, from the one declaration that sits beside the code
-- writing it (store.EnsureEntities, spec 6/37 step 7). An item needs no ALTER
-- to start carrying an attribute.
