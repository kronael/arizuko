-- A membership edge always carries `added_by`, and the empty string is what an
-- unattributed edge carries.
--
-- The attribute is the resource's own row filter: `acl_membership` excludes the
-- edges pairing consented to (`added_by = 'pairing'`) from the manifest-visible
-- projection, because a consented identity link is runtime state and not
-- declarative config. That filter is one declaration the export, the wholesale
-- delete and the scoped delete all honour, and on the object path a filter is a
-- CONJUNCTION of attribute comparisons with no OR in it (objstore.Query.Where).
--
-- `(added_by IS NULL OR added_by != 'pairing')` has no such form. `added_by <>
-- 'pairing'` does, and it is the same answer for every edge that carries a
-- value. Measured on all three live instances: 84 edges, every one of them
-- attributed, not a single absence. Making the value structural is what keeps a
-- later edge from falling out of its own resource's projection — invisible to
-- export, and untouched by the apply that should have replaced it. So
-- `arizuko migrate-routd` writes '' for an edge a pre-move database left
-- unattributed: it is a value both shapes can compare, where absence is not.
--
-- `acl_membership` is an objstore entity rather than a table this chain
-- creates: the driver makes it, from the one declaration that sits beside the
-- code writing it (store.EnsureEntities, spec 6/37 step 7), addressed by
-- (child, parent). There is no rebuild to do here.
