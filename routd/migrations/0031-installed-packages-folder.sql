-- an ordered product mix per GROUP, and a per-group mix cannot key into an
-- instance-keyed record (BUGS F30). The alternative was a second, group-scoped
-- lock — the "second package manager" 5/28 forbids in its own /migrate
-- paragraph. One lock, correctly keyed.
--
-- folder = '' means INSTANCE-WIDE, and that is not a sentinel this record
-- invented: network_rules is addressed by (folder, target) with '' for a global
-- rule. An install written by `arizuko packages install` — compose fragments,
-- proxyd routes, host files — belongs to no group and stamps ''.
--
-- The coordinate is the entity's sort key, so there is no rebuild to do here: a
-- key is what an item is addressed BY, and re-addressing the items a pre-move
-- database left behind is `arizuko migrate-routd`'s job — which is the run that
-- has to carry EVERY row, because this record is what `remove` reads to find
-- the routes, grants and files an install owns, and a row dropped there orphans
-- all of them silently.
--
-- `installed_packages` is an objstore entity rather than a table this chain
-- creates: the driver makes it, from the one declaration that sits beside the
-- code writing it (store.EnsureEntities, spec 6/37 step 7).
