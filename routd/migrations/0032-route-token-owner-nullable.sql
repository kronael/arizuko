-- alternative — a permanent sentinel group — is platform-manufactured operator
-- data, which root CLAUDE.md rules out.
--
-- Absence costs nothing functionally: neither PeekPairing nor RedeemPairing
-- reads owner_folder, and pair-kind items are already excluded from
-- ListRouteTokens and revokeRouteTokenTx (both filtered to kind='route').
--
