-- observe_window_messages, observe_window_chars, open — ride in one `config`
-- JSON attribute, so adding a setting costs no schema. container_config stays
-- its own attribute: it is spawn-specific and maps to core.GroupConfig.
--
-- `groups` is an objstore entity rather than a table this chain creates: the
-- driver makes it, from the one declaration that sits beside the code writing
-- it (store.EnsureEntities, spec 6/37 step 7). An attribute an item does not
-- carry is simply absent, which is the null this model has — so json_extract
-- yields NULL for an unset field and the Go layer applies its default, with no
-- column to add and none to drop. An entity keeps the name of the table it
-- replaces, so a database carrying group rows is moved by
-- `arizuko migrate-routd` and refuses to open until it has been.
